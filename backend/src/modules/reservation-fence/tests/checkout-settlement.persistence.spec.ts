function assertCatalogUpgrade(before: Catalog, after: Catalog): void {
  for (const kind of ['constraints', 'indexes', 'triggers', 'functions', 'enums'] as const) {
    const retained = before[kind].filter(row => kind !== 'indexes' || row.name !== 'checkout_reservation_resources_holdInstanceId_key');
    const oldNames = new Set(before[kind].map(row => row.name));
    expect(after[kind].filter(row => oldNames.has(row.name))).toEqual(retained);
    const additions = after[kind].filter(row => !oldNames.has(row.name));
    expect(Object.fromEntries(additions.map(row => [row.name, fingerprint(row.definition)]))).toEqual(migration46Catalog[kind]);
  }
}


